CREATE OR REPLACE FUNCTION public.set_collection_display_order(p_shelf_id uuid, p_collection_ids jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  if jsonb_typeof(p_collection_ids) <> 'array' then
    raise exception 'p_collection_ids must be a JSON array';
  end if;

  if p_shelf_id is null then
    with ordered as (
      select id_text, ordinality::integer as new_order
      from jsonb_array_elements_text(p_collection_ids) with ordinality as item(id_text, ordinality)
    )
    update public.collections c
    set sort_order = ordered.new_order
    from ordered
    where c.id::text = ordered.id_text
      and c.user_id = v_user_id;
  else
    if not exists (
      select 1
      from public.shelves s
      where s.id = p_shelf_id
        and s.user_id = v_user_id
    ) then
      raise exception 'Shelf not found';
    end if;

    with ordered as (
      select id_text, ordinality::integer as new_order
      from jsonb_array_elements_text(p_collection_ids) with ordinality as item(id_text, ordinality)
    )
    update public.collections c
    set shelf_sort_order = ordered.new_order
    from ordered
    where c.id::text = ordered.id_text
      and c.user_id = v_user_id
      and c.shelf_id = p_shelf_id;
  end if;
end;
$function$;

