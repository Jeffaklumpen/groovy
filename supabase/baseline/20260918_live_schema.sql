CREATE OR REPLACE FUNCTION public.delete_collection_record(p_collection_id text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := auth.uid();
  v_old_shelf_id uuid;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  select c.shelf_id
  into v_old_shelf_id
  from public.collections c
  where c.id::text = p_collection_id
    and c.user_id = v_user_id
  for update;

  if not found then
    raise exception 'Collection record not found';
  end if;

  delete from public.collections
  where id::text = p_collection_id
    and user_id = v_user_id;

  with ranked as (
    select
      c.id,
      row_number() over (order by c.sort_order nulls last, c.id) as new_order
    from public.collections c
    where c.user_id = v_user_id
  )
  update public.collections c
  set sort_order = ranked.new_order::integer
  from ranked
  where c.id = ranked.id;

  if v_old_shelf_id is not null then
    with ranked as (
      select
        c.id,
        row_number() over (
          order by c.shelf_sort_order nulls last, c.sort_order nulls last, c.id
        ) as new_order
      from public.collections c
      where c.user_id = v_user_id
        and c.shelf_id = v_old_shelf_id
    )
    update public.collections c
    set shelf_sort_order = ranked.new_order::integer
    from ranked
    where c.id = ranked.id;
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.delete_shelf_and_unshelve(p_shelf_id uuid)
 RETURNS integer
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := auth.uid();
  v_count integer := 0;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  if not exists (
    select 1
    from public.shelves s
    where s.id = p_shelf_id
      and s.user_id = v_user_id
  ) then
    raise exception 'Shelf not found';
  end if;

  update public.collections
  set shelf_id = null,
      shelf_sort_order = null
  where user_id = v_user_id
    and shelf_id = p_shelf_id;

  get diagnostics v_count = row_count;

  delete from public.shelves
  where id = p_shelf_id
    and user_id = v_user_id;

  return v_count;
end;
$function$;

CREATE OR REPLACE FUNCTION public.enforce_shelf_limit()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  perform pg_advisory_xact_lock(hashtext(new.user_id::text));

  if (
    select count(*)
    from public.shelves
    where user_id = new.user_id
  ) >= 10 then
    raise exception 'Maximum 10 shelves per user';
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_following_overview()
 RETURNS TABLE(user_id uuid, username text, avatar_url text, followed_at timestamp with time zone, collection_count bigint, wishlist_count bigint, common_count bigint)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
  select
    f.followed_id as user_id,
    p.username,
    p.avatar_url,
    f.created_at as followed_at,
    (select count(*) from public.collections c where c.user_id = f.followed_id)::bigint as collection_count,
    (select count(*) from public.wishlists w where w.user_id = f.followed_id)::bigint as wishlist_count,
    (
      select count(distinct mine.album_id)
      from public.collections mine
      left join public.albums mine_album on mine_album.id = mine.album_id
      where mine.user_id = auth.uid()
        and exists (
          select 1
          from public.collections theirs
          left join public.albums their_album on their_album.id = theirs.album_id
          where theirs.user_id = f.followed_id
            and (
              theirs.album_id = mine.album_id
              or (
                mine_album.discogs_master_id is not null
                and their_album.discogs_master_id = mine_album.discogs_master_id
              )
            )
        )
    )::bigint as common_count
  from public.user_follows f
  join public.profiles p on p.id = f.followed_id
  where f.follower_id = auth.uid()
  order by f.created_at desc;
$function$;

CREATE OR REPLACE FUNCTION public.get_following_statistics()
 RETURNS TABLE(user_id uuid, username text, avatar_url text, common_count bigint, taste_similarity numeric)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
  with followed as (
    select f.followed_id
    from public.user_follows f
    where f.follower_id = auth.uid()
  ),
  relevant_users as (
    select auth.uid() as user_id
    union
    select followed_id from followed
  ),
  genre_tokens as (
    select
      c.user_id,
      lower(btrim(token.genre_token)) as genre_token,
      count(*)::numeric as genre_count
    from public.collections c
    left join public.albums a on a.id = c.album_id
    join relevant_users ru on ru.user_id = c.user_id
    cross join lateral regexp_split_to_table(
      coalesce(nullif(btrim(c.discogs_style),''),nullif(btrim(a.genre),''),''),
      E'\\s*[·,]\\s*'
    ) as token(genre_token)
    where btrim(token.genre_token) <> ''
    group by c.user_id, lower(btrim(token.genre_token))
  ),
  genre_totals as (
    select user_id,sum(genre_count)::numeric as genre_total
    from genre_tokens
    group by user_id
  ),
  taste as (
    select
      f.followed_id,
      case
        when coalesce(own_total.genre_total,0) = 0 or coalesce(their_total.genre_total,0) = 0 then 0::numeric
        else round(
          coalesce(sum(least(
            own_genre.genre_count / own_total.genre_total,
            coalesce(their_genre.genre_count / their_total.genre_total,0)
          )),0) * 100,
          1
        )
      end as taste_similarity
    from followed f
    left join genre_totals own_total on own_total.user_id = auth.uid()
    left join genre_totals their_total on their_total.user_id = f.followed_id
    left join genre_tokens own_genre on own_genre.user_id = auth.uid()
    left join genre_tokens their_genre
      on their_genre.user_id = f.followed_id
     and their_genre.genre_token = own_genre.genre_token
    group by f.followed_id,own_total.genre_total,their_total.genre_total
  )
  select
    f.followed_id as user_id,
    p.username,
    p.avatar_url,
    (
      select count(distinct mine.album_id)
      from public.collections mine
      left join public.albums mine_album on mine_album.id = mine.album_id
      where mine.user_id = auth.uid()
        and exists (
          select 1
          from public.collections theirs
          left join public.albums their_album on their_album.id = theirs.album_id
          where theirs.user_id = f.followed_id
            and (
              theirs.album_id = mine.album_id
              or (
                mine_album.discogs_master_id is not null
                and their_album.discogs_master_id = mine_album.discogs_master_id
              )
            )
        )
    )::bigint as common_count,
    coalesce(t.taste_similarity,0)::numeric as taste_similarity
  from followed f
  join public.profiles p on p.id = f.followed_id
  left join taste t on t.followed_id = f.followed_id
  order by p.username;
$function$;

