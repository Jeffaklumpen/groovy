CREATE OR REPLACE FUNCTION public.upsert_apple_artwork_cache(p_matches jsonb)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  item jsonb;
  saved_count integer := 0;
  v_master_id bigint;
  v_artist text;
  v_title text;
  v_year integer;
  v_collection_id bigint;
  v_collection_url text;
  v_artwork_url text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if p_matches is null or jsonb_typeof(p_matches) <> 'array' then
    raise exception 'p_matches must be a JSON array';
  end if;

  if jsonb_array_length(p_matches) > 200 then
    raise exception 'Too many cache rows';
  end if;

  for item in
    select value from jsonb_array_elements(p_matches)
  loop
    begin
      v_master_id := nullif(item->>'discogs_master_id','')::bigint;
    exception when others then
      continue;
    end;

    v_artist := left(trim(coalesce(item->>'artist_name','')),300);
    v_title := left(trim(coalesce(item->>'album_title','')),500);

    begin
      v_year := nullif(item->>'release_year','')::integer;
    exception when others then
      v_year := null;
    end;

    if v_year is not null and (v_year < 1800 or v_year > 2100) then
      v_year := null;
    end if;

    begin
      v_collection_id := nullif(item->>'apple_collection_id','')::bigint;
    exception when others then
      v_collection_id := null;
    end;

    v_collection_url := left(trim(coalesce(item->>'apple_collection_url','')),1500);
    v_artwork_url := left(trim(coalesce(item->>'artwork_url','')),1500);

    if v_master_id is null or v_master_id <= 0 or v_artist = '' or v_title = '' then
      continue;
    end if;

    -- Only accept Apple's own album links and artwork CDN URLs.
    if v_collection_url !~* '^https://(music|itunes)\.apple\.com/' then
      continue;
    end if;

    if v_artwork_url !~* '^https://[^/]*mzstatic\.com/' then
      continue;
    end if;

    insert into public.apple_artwork_cache (
      discogs_master_id,
      artist_name,
      album_title,
      release_year,
      apple_collection_id,
      apple_collection_url,
      artwork_url,
      matched_at,
      updated_at
    ) values (
      v_master_id,
      v_artist,
      v_title,
      v_year,
      v_collection_id,
      v_collection_url,
      v_artwork_url,
      now(),
      now()
    )
    on conflict (discogs_master_id) do update set
      artist_name = excluded.artist_name,
      album_title = excluded.album_title,
      release_year = excluded.release_year,
      apple_collection_id = excluded.apple_collection_id,
      apple_collection_url = excluded.apple_collection_url,
      artwork_url = excluded.artwork_url,
      matched_at = now(),
      updated_at = now();

    saved_count := saved_count + 1;
  end loop;

  return saved_count;
end;
$function$;

CREATE OR REPLACE FUNCTION public.validate_collection_shelf_owner()
 RETURNS trigger
 LANGUAGE plpgsql
