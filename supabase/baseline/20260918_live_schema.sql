CREATE OR REPLACE FUNCTION public.move_collection_to_shelf(p_collection_id text, p_shelf_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user_id uuid := auth.uid();
  v_old_shelf_id uuid;
  v_new_order integer;
  v_result jsonb;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  select c.shelf_id
  into v_old_shelf_id
  from public.collections c
  where c.id::text = p_collection_id
    and c.user_id = v_user_id
  for update;

  if not found then
    raise exception 'Collection record not found';
  end if;

  if p_shelf_id is not null then
    perform 1
    from public.shelves s
    where s.id = p_shelf_id
      and s.user_id = v_user_id
    for update;

    if not found then
      raise exception 'Shelf not found';
    end if;
  end if;

  if v_old_shelf_id is not distinct from p_shelf_id then
    select jsonb_build_object(
      'shelf_id', c.shelf_id,
      'shelf_sort_order', c.shelf_sort_order
    )
    into v_result
    from public.collections c
    where c.id::text = p_collection_id
      and c.user_id = v_user_id;

    return v_result;
  end if;

  if p_shelf_id is null then
    update public.collections
    set shelf_id = null,
        shelf_sort_order = null
    where id::text = p_collection_id
      and user_id = v_user_id;
  else
    select coalesce(max(c.shelf_sort_order), 0) + 1
    into v_new_order
    from public.collections c
    where c.user_id = v_user_id
      and c.shelf_id = p_shelf_id;

    update public.collections
    set shelf_id = p_shelf_id,
        shelf_sort_order = v_new_order
    where id::text = p_collection_id
      and user_id = v_user_id;
  end if;

  if v_old_shelf_id is not null then
    with ranked as (
      select
        c.id,
        row_number() over (
          order by c.shelf_sort_order nulls last, c.sort_order nulls last, c.id
        ) as new_order
      from public.collections c
      where c.user_id = v_user_id
        and c.shelf_id = v_old_shelf_id
    )
    update public.collections c
    set shelf_sort_order = ranked.new_order::integer
    from ranked
    where c.id = ranked.id;
  end if;

  select jsonb_build_object(
    'shelf_id', c.shelf_id,
    'shelf_sort_order', c.shelf_sort_order
  )
  into v_result
  from public.collections c
  where c.id::text = p_collection_id
    and c.user_id = v_user_id;

  return v_result;
end;
$function$;

CREATE OR REPLACE FUNCTION public.notify_followers_collection_activity()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  follower record;
  existing_notification_id bigint;
  album_title text := '';
  album_artist text := '';
  album_cover text := '';
  recipient_has_album boolean := false;
  previous_shared_count integer := 0;
begin
  select
    coalesce(a.title,''),
    coalesce(ar.name,''),
    coalesce(new.cover_url,a.cover_url,'')
  into album_title, album_artist, album_cover
  from public.albums a
  left join public.artists ar on ar.id = a.artist_id
  where a.id = new.album_id;

  for follower in
    select uf.follower_id
    from public.user_follows uf
    where uf.followed_id = new.user_id
  loop
    select exists (
      select 1
      from public.collections mine
      left join public.albums mine_album on mine_album.id = mine.album_id
      left join public.albums added_album on added_album.id = new.album_id
      where mine.user_id = follower.follower_id
        and (
          mine.album_id = new.album_id
          or (
            added_album.discogs_master_id is not null
            and mine_album.discogs_master_id = added_album.discogs_master_id
          )
        )
    ) into recipient_has_album;

    existing_notification_id := null;

    update public.notifications n
    set
      item_count = n.item_count + 1,
      payload = coalesce(n.payload,'{}'::jsonb) || jsonb_build_object(
        'album_id', new.album_id,
        'album_title', album_title,
        'album_artist', album_artist,
        'cover_url', album_cover,
        'shared_count', coalesce(nullif(n.payload->>'shared_count','')::integer,0) + case when recipient_has_album then 1 else 0 end,
        'last_shared_album_title', case when recipient_has_album then album_title else coalesce(n.payload->>'last_shared_album_title','') end,
        'last_shared_album_artist', case when recipient_has_album then album_artist else coalesce(n.payload->>'last_shared_album_artist','') end
      ),
      updated_at = now()
    where n.recipient_id = follower.follower_id
      and n.actor_id = new.user_id
      and n.notification_type = 'collection_activity'
      and n.read_at is null
      and n.created_at >= now() - interval '2 hours'
    returning n.id into existing_notification_id;

    if existing_notification_id is null then
      insert into public.notifications (
        recipient_id,
        actor_id,
        notification_type,
        item_count,
        payload,
        created_at,
        updated_at
      ) values (
        follower.follower_id,
        new.user_id,
        'collection_activity',
        1,
        jsonb_build_object(
          'album_id', new.album_id,
          'album_title', album_title,
          'album_artist', album_artist,
          'cover_url', album_cover,
          'shared_count', case when recipient_has_album then 1 else 0 end,
          'last_shared_album_title', case when recipient_has_album then album_title else '' end,
          'last_shared_album_artist', case when recipient_has_album then album_artist else '' end
        ),
        now(),
        now()
      );
    end if;
  end loop;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.notify_followers_wishlist_match()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  follower record;
  existing_notification_id bigint;
  album_title text := '';
  album_artist text := '';
  album_cover text := '';
  recipient_has_album boolean := false;
begin
  select
    coalesce(a.title,''),
    coalesce(ar.name,''),
    coalesce(new.cover_url,a.cover_url,'')
  into album_title, album_artist, album_cover
  from public.albums a
  left join public.artists ar on ar.id = a.artist_id
  where a.id = new.album_id;

  for follower in
    select uf.follower_id
    from public.user_follows uf
    where uf.followed_id = new.user_id
  loop
    select exists (
      select 1
      from public.collections mine
      left join public.albums mine_album on mine_album.id = mine.album_id
      left join public.albums wish_album on wish_album.id = new.album_id
      where mine.user_id = follower.follower_id
        and (
          mine.album_id = new.album_id
          or (
            wish_album.discogs_master_id is not null
            and mine_album.discogs_master_id = wish_album.discogs_master_id
          )
        )
    ) into recipient_has_album;

    if recipient_has_album then
      existing_notification_id := null;

      update public.notifications n
      set
        item_count = n.item_count + 1,
        payload = coalesce(n.payload,'{}'::jsonb) || jsonb_build_object(
          'album_id', new.album_id,
          'album_title', album_title,
          'album_artist', album_artist,
          'cover_url', album_cover
        ),
        updated_at = now()
      where n.recipient_id = follower.follower_id
        and n.actor_id = new.user_id
        and n.notification_type = 'wishlist_match'
        and n.read_at is null
        and n.created_at >= now() - interval '2 hours'
      returning n.id into existing_notification_id;

      if existing_notification_id is null then
        insert into public.notifications (
          recipient_id,
          actor_id,
          notification_type,
          item_count,
          payload,
          created_at,
          updated_at
        ) values (
          follower.follower_id,
          new.user_id,
          'wishlist_match',
          1,
          jsonb_build_object(
            'album_id', new.album_id,
            'album_title', album_title,
            'album_artist', album_artist,
            'cover_url', album_cover
          ),
          now(),
          now()
        );
      end if;
    end if;
  end loop;

  return new;
end;
$function$;

